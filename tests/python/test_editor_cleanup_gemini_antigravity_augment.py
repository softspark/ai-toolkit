SymlinkCase = tuple[str, str, Setup, Call, Call]


def _link_setup(tmp_path: Path, relative: str, setup: Setup) -> tuple[Path, Path]:
    """Generate into ``outside`` and expose ``relative`` as a symlink to it."""
    outside = tmp_path / "outside"
    outside.mkdir()
    setup(outside)
    target = tmp_path / "target"
    link = target / relative
    link.parent.mkdir(parents=True)
    link.symlink_to(outside / relative, target_is_directory=True)
    return target, outside / relative


