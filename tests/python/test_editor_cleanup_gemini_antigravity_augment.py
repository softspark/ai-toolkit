@pytest.mark.parametrize(
    ("setup", "discover", "cleanup"),
    [surface[1:] for surface in SURFACES],
    ids=[surface[0] for surface in SURFACES],
)
def test_cleanup_removes_managed_and_keeps_user_files(
    tmp_path: Path, setup: Setup, discover: Call, cleanup: Call
) -> None:
    user_files = setup(tmp_path)
    before = {path: path.read_bytes() for path in user_files}

    found = discover(tmp_path)
    assert found > 0
    assert cleanup(tmp_path) == found

    for path, content in before.items():
        assert path.read_bytes() == content
    assert discover(tmp_path) == 0
    assert cleanup(tmp_path) == 0


