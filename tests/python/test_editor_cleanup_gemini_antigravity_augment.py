def _snapshot(root: Path) -> dict[str, bytes]:
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


@pytest.mark.parametrize(
    ("relative", "setup", "discover", "cleanup"),
    [case[1:] for case in SYMLINKED_ROOTS],
    ids=[case[0] for case in SYMLINKED_ROOTS],
)
def test_symlinked_root_is_refused(
    tmp_path: Path, relative: str, setup: Setup, discover: Call, cleanup: Call
) -> None:
    target, linked = _link_setup(tmp_path, relative, setup)
    before = _snapshot(linked)

    with pytest.raises(RuntimeError):
        discover(target)
    with pytest.raises(RuntimeError):
        cleanup(target)

    assert _snapshot(linked) == before


