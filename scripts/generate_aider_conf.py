"""Generate .aider.conf.yml configuration.

Without arguments, print the template. With a project directory, create its
.aider.conf.yml if missing.
"""
from __future__ import annotations

import argparse
import errno
import hashlib
import json
import os
import sys
import tempfile
from functools import partial
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _common import DEFAULT_CLAUDE_MODELS
from secure_fs import OwnedEdit, apply_owned_edits, lexical_absolute

GENERATED_HEADER = "# Aider configuration generated by ai-toolkit"
CHECKSUM_PREFIX = "# Original configuration SHA-256: "
# Exact released local templates, including their original model and comments.
LEGACY_LOCAL_DIGESTS = {
    "05b18eceb8f7e7de090e73646840f0cc6995a569643f22d0fd14a6688a0f7b55",  # v1.0.0
    "a8533da99a9a271b4c8237a968cf33672a797dcb260c7f763adba78a878f39d2",  # v2.0.0
    "9df77ea797fe8c17be6e2991f2d4b479c22551eab927bd84bdcbba5c75d4c50c",  # v3.0.0
    "cc8772bbb55420243d2fefba0b9fa0f12df38904b9d86df8fd0a57ad24d96796",  # v5.0.0
    "f0b9ad851a745eea89de59023c606144cbf1ac5f0e16d0c630a954909a8fcc88",  # v6.0.0
}
LEGACY_GLOBAL_MODELS = ("claude-sonnet-4-6", "claude-sonnet-5", "claude-sonnet-5-5")


def _stamp(body: str) -> str:
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return f"{GENERATED_HEADER}\n{CHECKSUM_PREFIX}{digest}\n{body}"


def _remove_if_pristine(content: bytes, *, directory: Path) -> bytes | None:
    normalized = content.replace(b"\r\n", b"\n")
    header, _, rest = normalized.partition(b"\n")
    if header != GENERATED_HEADER.encode():
        return content
    checksum, _, body = rest.partition(b"\n")
    if checksum.startswith(CHECKSUM_PREFIX.encode()):
        expected = CHECKSUM_PREFIX + hashlib.sha256(body).hexdigest()
        return None if checksum == expected.encode() else content
    if hashlib.sha256(normalized).hexdigest() in LEGACY_LOCAL_DIGESTS:
        return None
    legacy_path = f'"{directory / ".aider-ai-toolkit-CONVENTIONS.md"}"'
    if any(rest == _global_body(legacy_path, model).encode() for model in LEGACY_GLOBAL_MODELS):
        return None
    return content


def _cleanup_plan(target_dir: Path) -> tuple[Path, dict[Path, OwnedEdit]]:
    target = lexical_absolute(target_dir)
    path = target / ".aider.conf.yml"
    return target, ({path: partial(_remove_if_pristine, directory=target)} if path.is_file() else {})


def cleanup(target_dir: Path) -> int:
    """Delete ``target_dir/.aider.conf.yml`` only when the generated content is intact.

    Serves both scopes: a project root or HOME (``~/.aider.conf.yml``, which
    global install only creates when missing). Returns 1 when removed, else 0.
    """
    target, edits = _cleanup_plan(target_dir)
    return apply_owned_edits(edits, target, label="Aider config")


def discover(target_dir: Path) -> int:
    """Return 1 when :func:`cleanup` would remove the config, without side effects."""
    target, edits = _cleanup_plan(target_dir)
    return apply_owned_edits(edits, target, label="Aider config", dry_run=True)


