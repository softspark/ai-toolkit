def _global_body(quoted_path: str, model: str) -> str:
    return f"""# Aider docs: https://aider.chat/docs/config/aider_conf.html

architect: true
auto-accept-architect: true

read:
  - {quoted_path}

model: {model}
editor-model: {model}

commit-prompt: "Write a short, concise commit message following Conventional Commits (feat/fix/chore/docs/test/refactor)."
attribute-co-authored-by: false
attribute-commit-message-author: false
attribute-commit-message-committer: false
"""


def render_global_config(conventions: Path) -> str:
    quoted_path = json.dumps(str(conventions), ensure_ascii=False)
    return _stamp(_global_body(quoted_path, DEFAULT_CLAUDE_MODELS["sonnet"]))


def _create_exclusive(path: Path, content: str) -> bool:
    try:
        handle = path.open("x", encoding="utf-8")
    except FileExistsError:
        return False
    identity = os.fstat(handle.fileno())
    try:
        with handle:
            handle.write(content)
    except OSError:
        # Only roll back the inode this attempt created, never follow a link.
        try:
            if os.path.samestat(identity, path.lstat()):
                path.unlink()
        except FileNotFoundError:
            pass
        raise
    return True


def create_config_if_missing(path: Path, content: str) -> bool:
    """Install a config without replacing a file or following a symlink."""
    if os.path.lexists(path):
        return False
    with tempfile.TemporaryDirectory(dir=path.parent) as staging:
        staged = Path(staging) / "config"
        staged.write_text(content, encoding="utf-8")
        try:
            os.link(staged, path)
        except FileExistsError:
            return False
        except OSError as error:
            unsupported = error.errno in (errno.EPERM, errno.EACCES, errno.ENOSYS, errno.ENOTSUP)
            if not unsupported and getattr(error, "winerror", None) not in (1, 50):
                raise
            return _create_exclusive(path, content)
    return True


def install_local(target: Path) -> None:
    created = create_config_if_missing(target / ".aider.conf.yml", render_local_config())
    print("  Created: .aider.conf.yml" if created else "  Kept: existing .aider.conf.yml")


def main() -> None:
    print(render_local_config(), end="")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", type=Path, nargs="?")
    options = parser.parse_args()
    if options.project is None:
        main()
    else:
        install_local(options.project)
