"""Generate the ai-toolkit opencode plugin at ``.opencode/plugins/ai-toolkit-hooks.js``.

The default export supports OpenCode V2's ``id/setup`` contract and V1
1.18.29+'s ``server`` compatibility entrypoint. Older V1 versions must upgrade.
Docs: https://opencode.ai/v2/docs/build/plugins/server/#support-v1

This generator emits a single-file plugin that bridges ai-toolkit's
shared Bash hooks (``$HOME/.softspark/ai-toolkit/hooks/*.sh``) to
opencode lifecycle events. Coverage map:

  opencode event              -> ai-toolkit Bash hook(s)
  ---------------------------------------------------------------
  session.created             -> session-start.sh + mcp-health.sh
  session.compacted           -> pre-compact.sh + pre-compact-save.sh
  session.deleted             -> session-end.sh + save-session.sh
  message.updated             -> user-prompt-submit.sh + track-usage.sh
  message.part.updated        -> user-prompt-submit.sh + track-usage.sh
  tool.execute.before (bash)  -> guard-destructive.sh + commit-quality.sh
  tool.execute.after          -> post-tool-use.sh
  permission.asked            -> guard-destructive.sh
  command.executed            -> post-tool-use.sh

Security: hooks are spawned with a separate script-path argument (no
opencode-payload interpolation into the command). Event payloads are passed
on stdin as JSON. Advisory failures are logged. Pre-tool guards fail closed
on an explicit block, a crash, a timeout, or a missing executable.

Usage:
  python3 scripts/generate_opencode_plugin.py [target-dir] [--config-root PATH]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from secure_fs import (
    OwnedEdit, SecureDestination, SecureTransaction, apply_owned_edits,
    lexical_absolute, nearest_existing_root, run_secure_transaction,
)

PLUGIN_NAME = "ai-toolkit-hooks.js"
GENERATED_HEADER = b"// Auto-generated by ai-toolkit. Do not edit by hand"

PLUGIN_BODY = r"""// ai-toolkit opencode plugin — bridges shared Bash hooks to opencode events.
// Auto-generated by ai-toolkit. Do not edit by hand; re-run to update:
//   ai-toolkit opencode-plugin
// Docs: https://opencode.ai/v2/docs/build/plugins/server/#support-v1
// Requires OpenCode V2 or V1 >= 1.18.29.
//
// Hooks live at $HOME/.softspark/ai-toolkit/hooks/*.sh and are shared with
// Claude Code and Codex CLI. Node's child_process API is supported by both
// Node and Bun. Script arguments are separate from JSON stdin, so event
// payloads never become shell source.

import { spawn } from "node:child_process";

const HOOKS_DIR = `${process.env.HOME}/.softspark/ai-toolkit/hooks`;

// Global and project sources coexist in one server. Register both lifetimes,
// but elect one advisory executor per location. Safety guards always run,
// including during unload; advisory deduplication during reload is best effort.
const INSTANCES = Symbol.for("softspark.ai-toolkit.opencode.instances.v1");
function participate(directory, workspaceID) {
  const registry = globalThis[INSTANCES] ??= new Map();
  const key = JSON.stringify([directory, workspaceID ?? null]);
  const tokens = registry.get(key) ?? new Set();
  const token = Symbol();
  tokens.add(token);
  registry.set(key, tokens);
  return {
    active: () => tokens.values().next().value === token,
    release: () => {
      if (!tokens.delete(token)) return;
      if (tokens.size === 0 && registry.get(key) === tokens) registry.delete(key);
    },
  };
}

/** Shared Node/Bun process transport with separate arguments and stdin. */
function spawnHook(scriptPath, input, payload) {
  return new Promise((resolve, reject) => {
    const proc = spawn("bash", [scriptPath], {
      cwd: payload?.directory,
      env: { ...process.env, AI_TOOLKIT_EVENT: payload?.event || "unknown" },
      stdio: ["pipe", "ignore", "pipe"],
      timeout: 30000,
    });
    let stderr = "";
    proc.stderr.on("data", (chunk) => { stderr += chunk; });
    proc.on("error", reject);
    proc.stdin.on("error", (error) => {
      if (error.code !== "EPIPE") reject(error);
    });
    proc.on("close", (code) => resolve({ exitCode: code ?? 1, stderr }));
    proc.stdin.end(input);
  });
}

/** Invoke a Bash hook with a JSON payload on stdin. */
async function runHook(script, payload, blockOnFailure = false) {
  const scriptPath = `${HOOKS_DIR}/${script}`;
  let result;
  try {
    const input = JSON.stringify(payload ?? {});
    result = await spawnHook(scriptPath, input, payload);
  } catch (err) {
    if (blockOnFailure) {
      throw new Error(`[ai-toolkit] ${script} could not run: ${err.message}`);
    }
    process.stderr.write(`[ai-toolkit] failed to run ${script}: ${err.message}\n`);
    return 0;
  }
  if (result.exitCode === 2 && blockOnFailure) {
    const detail = result.stderr.toString().trim();
    throw new Error(
      `[ai-toolkit] ${script} blocked tool execution${detail ? `: ${detail}` : ""}`
    );
  }
  if (result.exitCode !== 0 && blockOnFailure) {
    throw new Error(`[ai-toolkit] ${script} failed (exit ${result.exitCode}): ${result.stderr.toString().trim()}`);
  }
  if (result.exitCode !== 0 && result.exitCode !== 2) {
    process.stderr.write(
      `[ai-toolkit] ${script} exited ${result.exitCode}\n${result.stderr.toString()}`
    );
  }
  return result.exitCode;
}

const AiToolkitHooks = async ({ project, directory, worktree, lease = participate(directory) }) => ({
  dispose: () => lease.release(),
  event: async ({ event }) => {
    if (!lease.active()) return;
    const payload = {
      event: event.type,
      session_id: event?.properties?.sessionID,
      project,
      directory,
      worktree,
    };
    switch (event.type) {
      case "session.created":
        await runHook("session-start.sh", payload);
        await runHook("mcp-health.sh", payload);
        break;
      case "session.compacted":
        await runHook("pre-compact.sh", payload);
        await runHook("pre-compact-save.sh", payload);
        break;
      case "session.deleted":
        await runHook("session-end.sh", payload);
        await runHook("save-session.sh", payload);
        break;
      case "message.updated":
      case "message.part.updated":
        await runHook("user-prompt-submit.sh", payload);
        await runHook("track-usage.sh", payload);
        break;
      case "permission.asked":
        await runHook("guard-destructive.sh", payload);
        break;
      case "command.executed":
        await runHook("post-tool-use.sh", payload);
        break;
    }
  },

  "tool.execute.before": async (input, output) => {
    const payload = {
      event: "tool.execute.before",
      session_id: input?.sessionID,
      tool_name: input?.tool,
      tool_input: output?.args,
      tool: input?.tool,
      args: output?.args,
      project,
      directory,
    };
    if (input?.tool === "bash" || input?.tool === "shell") {
      await runHook("guard-destructive.sh", payload, true);
      if (lease.active()) await runHook("commit-quality.sh", payload);
    }
  },

  "tool.execute.after": async (input, output) => {
    if (!lease.active()) return;
    const payload = {
      event: "tool.execute.after",
      session_id: input?.sessionID,
      tool_name: input?.tool,
      tool: input?.tool,
      result: output,
      project,
      directory,
    };
    await runHook("post-tool-use.sh", payload);
  },
});

// The single object is a documented dual-version entrypoint. Exporting the
// factory separately would make V1 load the same hooks twice.
export default {
  id: "ai-toolkit.project",
  server: AiToolkitHooks,
  async setup(ctx) {
    const lease = participate(ctx.location.directory, ctx.location.workspaceID);
    try {
      const { directory, project } = ctx.location;
      const hooks = await AiToolkitHooks({ directory, project, lease });
      await ctx.tool.hook("execute.before", (event) => hooks["tool.execute.before"](
        { tool: event.tool, sessionID: event.sessionID }, { args: event.input },
      ));
      await ctx.tool.hook("execute.after", (event) => hooks["tool.execute.after"](
        { tool: event.tool, sessionID: event.sessionID }, event.result ?? event.error,
      ));
      await ctx.session.hook("prompt", async (event) => {
        if (!lease.active()) return;
        const payload = { event: "prompt", session_id: event.sessionID,
          prompt: event.prompt.text, directory, project };
        await runHook("user-prompt-submit.sh", payload);
        await runHook("track-usage.sh", payload);
      });
      await ctx.session.hook("compaction", async (event) => {
        if (!lease.active()) return;
        const payload = { event: "compaction", session_id: event.sessionID, directory, project };
        await runHook("pre-compact.sh", payload);
        await runHook("pre-compact-save.sh", payload);
      });
      const controller = new AbortController();
      const events = (async () => {
        try {
          for await (const event of ctx.event.subscribe({
            types: ["session.created", "session.deleted"], signal: controller.signal,
          })) {
            const location = event.location ?? event.data?.location;
            if (location?.directory !== directory || location?.workspaceID !== ctx.location.workspaceID) continue;
            await hooks.event({ event: {
              type: event.type, properties: { sessionID: event.data.sessionID },
            } });
          }
        } catch (error) {
          if (!controller.signal.aborted) {
            lease.release();
            process.stderr.write(`[ai-toolkit] event subscription failed: ${error.message}\n`);
          }
        }
      })();
      return async () => { controller.abort(); lease.release(); await events; };
    } catch (error) {
      lease.release();
      throw error;
    }
  },
};
"""


def generate(target_dir: Path, config_root: Path | None = None) -> Path:
    """Write the opencode plugin file and return its path.

    ``config_root`` lets the caller override the default project-local
    layout. When omitted, writes to ``target_dir/.opencode/plugins/``.
    Pass ``config_root=~/.config/opencode`` to lay down the plugin
    globally at ``~/.config/opencode/plugins/ai-toolkit-hooks.js``.
    """
    base = lexical_absolute(config_root if config_root is not None else target_dir / ".opencode")
    path = base / "plugins" / PLUGIN_NAME
    destination = SecureDestination(path, nearest_existing_root(base), "OpenCode hook plugin")
    content = PLUGIN_BODY
    if config_root is not None:
        content = content.replace('id: "ai-toolkit.project"', 'id: "ai-toolkit.global"')

    def apply(transaction: SecureTransaction) -> None:
        existing = transaction.initial_content(destination)
        if existing is not None and GENERATED_HEADER not in existing[:512]:
            raise RuntimeError(f"Refusing user-owned OpenCode plugin: {path}")
        transaction.atomic_write(destination, content.encode(), 0o644)

    run_secure_transaction([destination], apply)
    return path


def _managed_edits(base: Path) -> dict[Path, OwnedEdit]:
    """Select the plugin only when it still carries the generated header."""
    plugins_dir = base / "plugins"
    for path in (base, plugins_dir):
        if path.is_symlink():
            raise RuntimeError(f"Refusing symlinked OpenCode path: {path}")
    plugin = plugins_dir / PLUGIN_NAME

    def remove_if_generated(content: bytes) -> bytes | None:
        return None if GENERATED_HEADER in content[:512] else content

    return {plugin: remove_if_generated} if plugin.is_file() else {}


def cleanup(target_dir: Path, config_root: Path | None = None) -> int:
    """Remove the generated hook plugin; return 1 when removed, else 0."""
    base = config_root if config_root is not None else target_dir / ".opencode"
    return apply_owned_edits(
        _managed_edits(base),
        lexical_absolute(target_dir),
        label="OpenCode plugin",
        prune=(base / "plugins", base),
    )


def discover(target_dir: Path, config_root: Path | None = None) -> int:
    """Return 1 when :func:`cleanup` would remove the plugin, without side effects."""
    base = config_root if config_root is not None else target_dir / ".opencode"
    return apply_owned_edits(
        _managed_edits(base),
        lexical_absolute(target_dir),
        label="OpenCode plugin",
        dry_run=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate opencode plugin")
    parser.add_argument("target", nargs="?", default=".", help="Target directory")
    parser.add_argument(
        "--config-root",
        type=Path,
        default=None,
        help="Override base (e.g. ~/.config/opencode for global install).",
    )
    args = parser.parse_args()
    target = Path(args.target)
    path = generate(target, config_root=args.config_root)
    try:
        rel = path.relative_to(target)
    except ValueError:
        rel = path
    print(f"Generated: {rel}")


if __name__ == "__main__":
    main()
